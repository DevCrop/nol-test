import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root = new URL('../nol-gate/resource/previews/', import.meta.url);
const html = fs.readFileSync(new URL('temporary-password.html', root), 'utf8');
const source = fs.readFileSync(new URL('temporary-password.js', root), 'utf8');
new vm.Script(source.replace('export function', 'function'));
const context = vm.createContext({});
const checksSource = source.slice(source.indexOf('export function passwordChecks'), source.indexOf('\nfunction refresh'));
vm.runInContext(checksSource.replace('export function', 'function'), context);
const checks = context.passwordChecks;
let passed = 0;
function test(name, fn) { fn(); passed++; console.log('PASS ' + name); }
test('empty rejected', () => assert.equal(checks('', '').length, false));
test('short rejected', () => assert.equal(checks('Ab1!', 'Ab1!').length, false));
test('valid example accepted', () => { const state = checks('Preview123!', 'Preview123!'); assert.ok(state.length && state.mix && state.match); });
test('mismatch rejected', () => assert.equal(checks('Preview123!', 'Preview123?').match, false));
test('missing number rejected', () => assert.equal(checks('Preview!!!!', '').mix, false));
test('missing letter rejected', () => assert.equal(checks('12345678!!', '').mix, false));
test('missing special rejected', () => assert.equal(checks('Preview123', '').mix, false));
test('spaces rejected', () => assert.equal(checks('Preview 123!', '').mix, false));
test('overlength rejected', () => assert.equal(checks('A1!' + 'x'.repeat(62), '').length, false));
test('module script loads', () => assert.match(html, /type="module" src="temporary-password.js/));
test('no network or storage code', () => assert.doesNotMatch(source, /\b(fetch|XMLHttpRequest|localStorage|sessionStorage|sendBeacon)\b/));
test('form submission intercepted', () => assert.match(source, /event\.preventDefault\(\)/));
test('preview warning visible', () => assert.ok(html.includes('실제 계정 및 비밀번호는 변경되지 않습니다.')));
test('success and admin isolated panels', () => { assert.match(html, /id="success-panel"[^>]*hidden/); assert.match(html, /id="admin-panel"[^>]*hidden/); });
test('existing admin stylesheet reused', () => assert.match(html, /href="\.\.\/css\/style.css"/));
test('existing auth components reused', () => { for (const name of ['no-sub-body', 'no-login-header', 'no-login-wrap', 'no-login-top', 'no-auth-field', 'no-auth-input', 'no-pwd-btn', 'no-btn--submit', 'no-login-footer']) assert.ok(html.includes(name), name); });
test('no duplicate base component styling', () => { const css = fs.readFileSync(new URL('temporary-password.css', root), 'utf8'); assert.doesNotMatch(css, /\.no-(?:auth-input|btn--submit|login-title|login-wrap)\s*\{/); });
console.log(`pass=${passed} fail=0`);
